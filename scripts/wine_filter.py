#!/usr/bin/env python3
"""
楽天商品が「日本ワイン（またはワイナリー由来の果実酒）」かどうかを判定する共通フィルタ。
fetch_rakuten_items.py と regenerate_all_pages.py の両方から使う。

方針: 精度優先（False Positiveを絶対に出さない）。
  - 明確な非ワイン語（服飾・雑貨・書籍・他カテゴリ酒類など）があれば除外
  - ワイン/ぶどう品種/醸造/ボトル容量などのワインシグナルが無ければ除外
ワインかどうか確信が持てないものは「載せない」（= 違うものを入れない）。
"""
import re

# 明確な非ワイン（これが含まれたら問答無用で除外）
# 非飲料（服飾・雑貨・食器・書籍など）。これがあればワイン語があっても問答無用で除外
# （例「ワイングラス」「ワインバー 前菜皿」はワインではなく用品）
_EXCLUDE_HARD = re.compile(
    # 服飾
    r'カーディガン|スカート|ニット|セーター|シャツ|ブラウス|ワンピース|パンツ|デニム|ジーンズ'
    r'|コート|ジャケット|アウター|トップス|ボトムス|パーカー|スウェット|レギンス|ストッキング'
    r'|ランジェリー|インナー|ルームウェア|下着|ショーツ|ブラジャー|靴下|レッグウェア|ウェア\b'
    # 車・インテリア・食品など（同名ブランドの誤マッチ対策）
    r'|マット|ラグ|ラゲッジ|フロアマット|カーマット|カー用品|車用|クッション|カーテン|タオル|寝具'
    r'|ビネガー|ジャム|ドレッシング|レトルト|ソーセージ|チョコレート|クッキー|焼き菓子'
    # 雑貨・アクセサリ（「リング」「ケース」は スパークリング/24本入ケース に誤マッチするため使わない）
    r'|バッグ|\bbag\b|カバン|鞄|財布|ポーチ|リュック|ピアス|イヤリング|ネックレス|ブレスレット'
    r'|指輪|アクセサリ|腕時計|掛け時計|スニーカー|シューズ|サンダル|ブーツ|帽子|マフラー'
    r'|手袋|サングラス|メガネ|眼鏡|スマホケース|スマートフォンケース|iphoneケース|手芸|ビジューパーツ|手芸パーツ'
    r'|フードパック|OPP袋|レースバック|食品トレー|ラッピング袋'
    # グラス・食器・ワイン用品（「スクリューキャップ/コルクキャップ」「モントグラス」等の誤爆を避け複合語で限定）
    r'|ワイングラス|ペアグラス|ロックグラス|ボヘミアングラス|タンブラーグラス|グラスセット|グラスホルダー|グラススタンド|グラス収納|グラス\s?\d+個'
    r'|食器|プレート|ボウル|カトラリー|栓抜き|コルク抜き|ワインオープナー'
    r'|お皿|取り皿|小皿|大皿|中皿|ケーキ皿|前菜皿|パスタ皿'
    r'|ソムリエナイフ|デカンタ|デキャンタ|ワインセラー|ワインクーラー|ワインラック|ボトルホルダー|コースター'
    # 書籍・電子書籍
    r'|電子書籍|\bebook\b|kindle|楽天kobo|文庫|新書|コミック|単行本'
    # 非ワインの飲料・食品・雑貨（茶葉/ジュース/石鹸/ブランデー等。化粧箱・ジャパンワインは誤爆しない語に限定）
    r'|茶葉|リーフティー|ハーブティー|北海道tea|ジュース|\bjuice\b|石鹸|石けん|ぶどうの葉|ブランデー|コニャック|蒸留酒',
    re.IGNORECASE,
)

# 他カテゴリの酒類。ワインシグナルが無い場合のみ除外（「○○ワイン ミスタージンギスカン」等を守る）
_EXCLUDE_BOOZE = re.compile(
    r'ウイスキー|ウィスキー|whisky|whiskey|シングルモルト|バーボン|スコッチ'
    r'|焼酎|泡盛|日本酒|純米酒|吟醸|本醸造|大吟醸|清酒'
    r'|\bジン\b|ジントニック|\bgin\b|ウォッカ|vodka|ラム酒|テキーラ|リキュール|梅酒|ビール|発泡酒|ハイボール'
    r'|ブランデー|コニャック|ニューポット',
    re.IGNORECASE,
)

# ワインであるシグナル（いずれか1つ以上必須）
_WINE = re.compile(
    # 「ワイン」は色名/菓子/調味料用途（ワインレッド・ワインケーキ・ワインビネガー等）を否定先読みで除外
    r'ワイン(?!レッド|カラー|色|ビネガー|バー|風呂|染|味|煮|ケーキ|ゼリー|グミ|キャンディ|キャンデー|チョコ|ジャム|クーラー|セラー|グラス|ラック)'
    r'|\bwine\b|ヴァン|\bvin\b|スパークリング|スプマンテ|spumante|フリザンテ|ペティアン|ヌーヴ|ヌーボ|シードル|\bcidre\b'
    # ぶどう品種
    r'|甲州|マスカット.?ベ[ーェ]?リ[ーィ]?Ａ?|ベ[ーェ]リ[ーィ]?Ａ|メルロ|シャルドネ|ピノ|カベルネ'
    r'|ツヴァイ|ケルナー|デラウェア|ソーヴィニヨン|ソービニヨン|リースリング|ナイアガラ|セミヨン'
    r'|シラー|サンジョベーゼ|タナ|プティ.?ヴェルド|ヴィオニエ|ゲヴュルツ|巨峰|葡萄|ぶどう|ブドウ'
    # 醸造・ワイナリー用語
    r'|醸造|ワイナリー|ヴィンヤード|vineyard|domaine|ドメーヌ|château|chateau|シャトー'
    r'|cuv[ée]e|キュヴェ|ボジョレ|ボージョレ|テロワール|果実酒'
    # 自然派・仏語表記（ブラン=白/ルージュ=赤/サンスフル=無亜硫酸 等）
    r'|ブラン|ルージュ|\bblanc\b|\brouge\b|サンスフル|サン・スフル|ナチュール|ペットナット|ペット・ナット|微発泡|無濾過|生詰'
    # ワインの色・タイプ（赤白ロゼ）
    r'|赤ワイン|白ワイン|ロゼ',
    re.IGNORECASE,
)

# ワインボトルの定番容量（補助シグナル：除外語が無く容量があればワインとみなす）
_VOL = re.compile(r'\b(750|720|375|360)\s?ml\b', re.IGNORECASE)


def is_wine_item(name: str) -> bool:
    """商品名がワイン（またはワイナリー由来の果実酒）として妥当ならTrue。"""
    if not name:
        return False
    # 1) 非飲料（服飾・食器・書籍等）は無条件で除外
    if _EXCLUDE_HARD.search(name):
        return False
    # 2) ワインシグナルがあればワイン（他酒類語の付随的言及より優先）
    if _WINE.search(name):
        return True
    # 3) 他カテゴリの酒類（ウイスキー・日本酒・ジン等）は除外
    if _EXCLUDE_BOOZE.search(name):
        return False
    # 4) ワイン語は無いが除外語も無く・ワインボトル定番容量がある → ワインとみなす
    if _VOL.search(name):
        return True
    return False


