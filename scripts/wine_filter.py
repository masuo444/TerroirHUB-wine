#!/usr/bin/env python3
"""
楽天商品が「日本ワイン（またはワイナリー由来の果実酒）」かどうかを判定する共通フィルタ。
fetch_rakuten_items.py と regenerate_all_pages.py の両方から使う。

方針: 精度優先（False Positiveを絶対に出さない）。
  - 明確な非ワイン語（服飾・雑貨・書籍・他カテゴリ酒類など）があれば除外
  - ワイン/ぶどう品種/醸造/ボトル容量などのワインシグナルが無ければ除外
ワインかどうか確信が持てないものは「載せない」（= 違うものを入れない）。
"""
import re

# 明確な非ワイン（これが含まれたら問答無用で除外）
_EXCLUDE = re.compile(
    # 服飾
    r'カーディガン|スカート|ニット|セーター|シャツ|ブラウス|ワンピース|パンツ|デニム|ジーンズ'
    r'|コート|ジャケット|アウター|トップス|ボトムス|パーカー|スウェット|レギンス|ストッキング'
    # 雑貨・アクセサリ（「リング」「ケース」は スパークリング/24本入ケース に誤マッチするため使わない）
    r'|バッグ|\bbag\b|カバン|鞄|財布|ポーチ|リュック|ピアス|イヤリング|ネックレス|ブレスレット'
    r'|指輪|アクセサリ|腕時計|掛け時計|スニーカー|シューズ|サンダル|ブーツ|帽子|キャップ|マフラー'
    r'|手袋|サングラス|メガネ|眼鏡|スマホケース|スマートフォンケース|iphoneケース|手芸|ビジューパーツ|手芸パーツ'
    r'|フードパック|OPP袋|レースバック|食品トレー|ラッピング袋'
    # 書籍・電子書籍
    r'|電子書籍|\bebook\b|kindle|楽天kobo|文庫|新書|コミック|単行本'
    # 他カテゴリの酒類（ワインサイトには載せない）
    r'|ウイスキー|ウィスキー|whisky|whiskey|シングルモルト|バーボン|スコッチ'
    r'|焼酎|泡盛|日本酒|純米|吟醸|本醸造|大吟醸|清酒'
    r'|ジン|\bgin\b|ウォッカ|vodka|ラム酒|テキーラ|リキュール|梅酒|ビール|発泡酒|ハイボール'
    r'|ブランデー|コニャック|ニューポット',
    re.IGNORECASE,
)

# ワインであるシグナル（いずれか1つ以上必須）
_WINE = re.compile(
    r'ワイン|\bwine\b|ヴァン|\bvin\b|スパークリング|スプマンテ|spumante|フリザンテ|ペティアン|ヌーヴ|ヌーボ|シードル|\bcidre\b'
    # ぶどう品種
    r'|甲州|マスカット.?ベ[ーェ]?リ[ーィ]?Ａ?|ベ[ーェ]リ[ーィ]?Ａ|メルロ|シャルドネ|ピノ|カベルネ'
    r'|ツヴァイ|ケルナー|デラウェア|ソーヴィニヨン|ソービニヨン|リースリング|ナイアガラ|セミヨン'
    r'|シラー|サンジョベーゼ|タナ|プティ.?ヴェルド|ヴィオニエ|ゲヴュルツ|巨峰|葡萄|ぶどう|ブドウ'
    # 醸造・ワイナリー用語
    r'|醸造|ワイナリー|ヴィンヤード|vineyard|domaine|ドメーヌ|château|chateau|シャトー'
    r'|cuv[ée]e|キュヴェ|ボジョレ|ボージョレ|テロワール|果実酒'
    # ワインの色・タイプ（赤白ロゼ）
    r'|赤ワイン|白ワイン|ロゼ',
    re.IGNORECASE,
)

# ワインボトルの定番容量（補助シグナル：除外語が無く容量があればワインとみなす）
_VOL = re.compile(r'\b(750|720|375|360)\s?ml\b', re.IGNORECASE)


def is_wine_item(name: str) -> bool:
    """商品名がワイン（またはワイナリー由来の果実酒）として妥当ならTrue。"""
    if not name:
        return False
    if _EXCLUDE.search(name):
        return False
    if _WINE.search(name):
        return True
    # ワイン語は無いが、除外語も無く・ワインボトル容量がある → ワインとみなす
    if _VOL.search(name):
        return True
    return False


if __name__ == '__main__':
    # 簡易自己テスト
    tests = [
        ('【中央葡萄酒】グレイスワイン グリド甲州 750ml', True),
        ('GRACE CONTINENTAL オーバーニットカーディガン', False),
        ('サントリー 山崎 12年 シングルモルト ウイスキー', False),
        ('手芸パーツ ビジューセンターパーツ OSA-5', False),
        ('ニッカ弘前 生シードル スイート 200ml瓶 24本入ケース スパークリングワイン', True),
        ('十和田ワイン ニホンヤマブドウブレンド 赤 720ml×12本【1ケース】', True),
        ('[2021] 弘前スプマンテ FATTORIA DA SASINO', True),
        ('GRACE CONTINENTAL ティアードニットスカート 指輪付き', False),
        ('馬追蒸留所 MYAOI Gin ミャオイ ジン', False),
        ('Due punti di vista 電子書籍', False),
        ('椀子 メルロー 赤 750ml', True),
        ('ココ・ファーム のぼ赤 720ml', True),
    ]
    ok = 0
    for nm, exp in tests:
        got = is_wine_item(nm)
        mark = 'OK' if got == exp else 'NG'
        if got == exp:
            ok += 1
        print(f'  [{mark}] {got!s:5} (期待{exp!s:5}) {nm}')
    print(f'\n{ok}/{len(tests)} passed')
